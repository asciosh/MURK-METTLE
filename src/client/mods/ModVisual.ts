import * as THREE from 'three';
import { GLTFLoader, type GLTF } from 'three/addons/loaders/GLTFLoader.js';
import type { ValidatedMod } from './format.mjs';
export function disposeAsset(gltf: GLTF): void {
  const images = new Set<ImageBitmap>();
  const geometries = new Set<THREE.BufferGeometry>(),
    materials = new Set<THREE.Material>(),
    textures = new Set<THREE.Texture>();
  gltf.scene.traverse((o) => {
    if (o instanceof THREE.Mesh) {
      geometries.add(o.geometry);
      for (const m of Array.isArray(o.material) ? o.material : [o.material]) {
        materials.add(m);
        for (const v of Object.values(m)) if (v instanceof THREE.Texture) textures.add(v);
      }
    }
  });
  geometries.forEach((g) => g.dispose());
  materials.forEach((m) => m.dispose());
  textures.forEach((t) => {
    t.dispose();
    const image = t.source.data;
    if (typeof ImageBitmap !== 'undefined' && image instanceof ImageBitmap) images.add(image);
  });
  images.forEach((image) => image.close());
}
export async function loadValidated(mod: ValidatedMod): Promise<GLTF> {
  const urls = new Map<string, string>();
  for (const name of mod.manifest.textures || [])
    urls.set(name, URL.createObjectURL(new Blob([mod.files.get(name)!], { type: 'image/png' })));
  const manager = new THREE.LoadingManager();
  manager.setURLModifier((url) => {
    const local = urls.get(url);
    if (local) return local;
    // Embedded images are generated by GLTFLoader itself; all input blob/data/http URIs were rejected by validation.
    if (url.startsWith('blob:')) return url;
    throw Error('Only validated package images may be loaded');
  });
  const loader = new GLTFLoader(manager);
  let asset: GLTF | undefined;
  try {
    asset = await loader.parseAsync(mod.files.get(mod.manifest.model)!.buffer, '');
    // Do not trust author-supplied accessor min/max as culling bounds.
    asset.scene.traverse((node) => {
      if (node instanceof THREE.Mesh) {
        node.geometry.computeBoundingBox();
        node.geometry.computeBoundingSphere();
      }
    });
    const box = new THREE.Box3().setFromObject(asset.scene),
      extent = box.getSize(new THREE.Vector3()).length();
    if (!Number.isFinite(extent) || extent < 0.001) throw Error('The model has no finite visible bounds');
    return asset;
  } catch (error) {
    if (asset) disposeAsset(asset);
    throw error;
  } finally {
    for (const url of urls.values()) URL.revokeObjectURL(url);
  }
}
export class ModVisual {
  readonly root = new THREE.Group();
  private readonly mesh: THREE.Object3D;
  private readonly mixer: THREE.AnimationMixer;
  private action: THREE.AnimationAction | null = null;
  private state = '';
  private restart = false;
  private pulseRemaining = 0;
  private disposed = false;
  private readonly materials: THREE.MeshStandardMaterial[] = [];
  private readonly baseEmissive = new Map<THREE.MeshStandardMaterial, number>();
  constructor(
    private readonly asset: GLTF,
    readonly mod: ValidatedMod,
    private readonly release: () => void,
  ) {
    this.mesh = asset.scene.clone(true);
    // V1 rejects skins and morph targets: geometry/textures are shared; each visual owns its materials and mixer.
    const copies = new Map<THREE.Material, THREE.Material>();
    this.mesh.traverse((o) => {
      if (!(o instanceof THREE.Mesh)) return;
      o.castShadow = o.receiveShadow = true;
      const own = (m: THREE.Material) => {
        let c = copies.get(m);
        if (!c) {
          c = m.clone();
          copies.set(m, c);
          if (c instanceof THREE.MeshStandardMaterial) {
            c.envMapIntensity = 0.6;
            c.roughness = Math.max(0.35, c.roughness);
            this.materials.push(c);
            this.baseEmissive.set(c, c.emissiveIntensity);
          }
        }
        return c;
      };
      o.material = Array.isArray(o.material) ? o.material.map(own) : own(o.material);
    });
    this.root.add(this.mesh);
    this.root.scale.setScalar(0.75 / mod.stats.radius); // Conservative radius across all allowed rotation tracks.
    this.mixer = new THREE.AnimationMixer(this.mesh);
  }
  pulse(): void {
    this.pulseRemaining = 0.65;
    this.state = '';
    this.restart = true;
  }
  update(dt: number, moving: boolean, effects = true): void {
    if (this.disposed) return;
    this.pulseRemaining = Math.max(0, this.pulseRemaining - dt);
    const state = this.pulseRemaining > 0 ? 'pulse' : moving ? 'walk' : 'idle';
    if (state !== this.state) {
      this.state = state;
      const mapping = this.mod.manifest.animations || {},
        clipName = mapping[state as keyof typeof mapping] || mapping.idle;
      const clip =
        this.asset.animations.find((c) => c.name === clipName) ||
        this.asset.animations.find((c) => c.name === mapping.idle);
      if (clip) {
        const next = this.mixer.clipAction(clip);
        const once = state === 'pulse' && clip.name === mapping.pulse;
        next.setLoop(once ? THREE.LoopOnce : THREE.LoopRepeat, once ? 1 : Infinity);
        next.clampWhenFinished = once;
        if (next !== this.action || this.restart) {
          next.reset().play();
          if (this.action && next !== this.action) next.crossFadeFrom(this.action, 0.16, false);
          this.action = next;
        }
      }
    }
    this.restart = false;
    this.mixer.update(Math.max(0, Math.min(dt, 0.15)));
    const strength = effects ? this.mod.manifest.effects?.[0]?.strength || 0 : 0;
    for (const m of this.materials)
      m.emissiveIntensity =
        (this.baseEmissive.get(m) || 0) + strength * Math.sin((Math.PI * this.pulseRemaining) / 0.65) * 0.6;
  }
  dispose(): void {
    if (this.disposed) return;
    this.disposed = true;
    this.mixer.stopAllAction();
    this.mixer.uncacheRoot(this.mesh);
    this.materials.forEach((m) => m.dispose());
    this.root.removeFromParent();
    this.release();
  }
}
